const LOCALE_ID = /^[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]{2,8})*$/;

/** Keeps well-formed locale ids (ko-KR, en_US, yue-CN), at most 3, without repeats; empty means automatic. */
export function normalizeSpeechLanguages(value: unknown): readonly string[] {
	const list = typeof value === "string" ? value.split(",") : Array.isArray(value) ? value : [];
	const languages: string[] = [];
	for (const entry of list) {
		if (typeof entry !== "string") continue;
		const id = entry.trim().replace(/_/g, "-");
		if (!LOCALE_ID.test(id) || languages.some((known) => known.toLowerCase() === id.toLowerCase())) continue;
		languages.push(id);
		if (languages.length === 3) break;
	}
	return languages;
}

export function uiLanguageOf(locale: string | undefined): UiLanguage | undefined {
	const language = (locale ?? "").toLowerCase().split(/[-_]/)[0];
	return UI_LANGUAGES.find((candidate) => candidate === language);
}

export function systemLocale(): string {
	return Intl.DateTimeFormat().resolvedOptions().locale;
}

/**
 * The language buddy talks in: the one the person just spoke, else the settings language, else the Mac's, else
 * English.
 */
export function replyLanguage(spoken: string | undefined, uiLanguage: string, system: string = systemLocale()) {
	return uiLanguageOf(spoken) ?? uiLanguageOf(uiLanguage) ?? uiLanguageOf(system) ?? "en";
}

